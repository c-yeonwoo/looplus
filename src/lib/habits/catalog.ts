export function searchTemplates(query: string): readonly HabitTemplate[] {
  const words = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return HABIT_TEMPLATES.filter((t) =>
    words.every((word) =>
      `${t.title} ${t.category} ${t.keywords}`
        .toLocaleLowerCase()
        .includes(word),
    ),
  );
}
